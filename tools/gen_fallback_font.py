g('8', '.###./#...#/#...#/.###./#...#/#...#/.###.')
g('9', '.###./#...#/#...#/.####/....#/...#./.##..')
g(':', '..#../...../...../...../..#..', 2)
g(';', '..#../...../...../...../..#../.#...', 2)
g('<', '...#./..#../.#.../#..../.#.../..#../...#.')
g('=', '#####/...../#####', 2)
