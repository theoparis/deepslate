#!/usr/bin/env python3
"""Generates src/assets/fallback_font.cpp: a hand-drawn 5x7 bitmap font laid out like the
vanilla `assets/minecraft/textures/font/ascii.png` (128x128, 16x16 grid of 8x8 cells).
Only used when no resource pack provides the real font.  Usage: gen_fallback_font.py > out.cpp"""
import struct, sys, zlib

# char -> (first row, rows)   rows are 5 chars wide; '#' = pixel
G = {}
def g(ch, rows, start=0):
    G[ch] = (start, rows.split('/'))

g('!', '..#../..#../..#../..#../..#../...../..#..')
g('"', '.#.#./.#.#./.#.#.')
g('#', '.#.#./.#.#./#####/.#.#./#####/.#.#./.#.#.')
