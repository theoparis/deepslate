g('}', '.##../..#../..#../...#./..#../..#../.##..')
g('~', '.##.#/#.##.', 2)

W = H = 128
px = bytearray(W * H * 4)
for ch, (start, rows) in G.items():
    c = ord(ch)
    cx, cy = (c % 16) * 8, (c // 16) * 8
    for r, line in enumerate(rows):
        for x, v in enumerate(line):
            if v == '#':
                y = cy + start + r
                i = (y * W + cx + x) * 4
                px[i:i + 4] = b'\xff\xff\xff\xff'

def png(w, h, rgba):
    raw = b''.join(b'\x00' + bytes(rgba[y * w * 4:(y + 1) * w * 4]) for y in range(h))
    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')

data = png(W, H, px)
if len(sys.argv) > 1:
    open(sys.argv[1], 'wb').write(data)
out = ["// Generated by tools/gen_fallback_font.py (hand-drawn 5x7 glyphs in 8x8 cells). Do not edit.",
       "namespace ds {",
       "extern const unsigned char kFallbackFontPng[];", "extern const unsigned int kFallbackFontPngSize;",
       "const unsigned char kFallbackFontPng[] = {"]
for i in range(0, len(data), 24):
    out.append(",".join(str(b) for b in data[i:i + 24]) + ",")
out.append("};")
out.append(f"const unsigned int kFallbackFontPngSize = {len(data)};")
out.append("}  // namespace ds")
print("\n".join(out))
